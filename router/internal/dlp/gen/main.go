// Command gen regenerates configs/dlp.example.yaml from dlp.DefaultRules so
// the example file never drifts from the built-in set. Run from the router
// module root:
//
//	go run ./internal/dlp/gen
//
// A test in internal/dlp asserts the file parses back to the same rules.
package main

import (
	"fmt"
	"log"
	"os"
	"strings"

	"github.com/openscope/openscope/router/internal/dlp"
)

func yamlQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

func main() {
	f, err := os.Create("configs/dlp.example.yaml")
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	fmt.Fprintln(f, `# OpenScope DLP ruleset — the built-in rules expressed as YAML.
#
# Point the router at a file like this with OPENSCOPE_DLP_RULES_FILE.
#   mode: extend   — your rules are added to the built-ins (same id overrides)
#   mode: replace  — ONLY the rules in this file are active
#
# This file uses "replace" and lists the full built-in set, so it behaves
# identically to running with no rules file: edit from here to customize.
#
# Categories: content-class | classification | export-control | foundry-nda
#             | secret | pii
# Severities: critical | high | medium | low
# min_hits:   matches required before the rule fires (0/1 = any match)
#
# Generated by: go run ./internal/dlp/gen — do not edit the rule list by
# hand here without also updating patterns.go (or your own copy elsewhere).

version: 1
mode: replace
rules:`)
	for _, r := range dlp.DefaultRules {
		fmt.Fprintf(f, "  - id: %s\n", r.ID)
		fmt.Fprintf(f, "    name: %s\n", yamlQuote(r.Name))
		fmt.Fprintf(f, "    category: %s\n", r.Category)
		fmt.Fprintf(f, "    severity: %s\n", r.Severity)
		fmt.Fprintf(f, "    min_hits: %d\n", r.MinHits)
		fmt.Fprintf(f, "    pattern: %s\n", yamlQuote(r.Pattern.String()))
	}
}
